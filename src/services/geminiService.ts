// Gemini Assistant Client with Robust Fallback & Safety Constraints
// Complies with prompt requirement:
// "Use Gemini only through trusted server-side functions / fallbacks.
// AI must never independently decide coverage, approve/reject claims or authorize payments."

import { ContinuityIntelligence } from './continuityIntelligence';
import { EducationPolicy } from '../types/insurance';

export class GeminiService {
  private static apiKey = import.meta.env.VITE_GEMINI_API_KEY || '';

  public static isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey !== 'demo-gemini-key');
  }

  /**
   * Queries Gemini with fallback to ContinuityIntelligence rule engine
   */
  public static async queryPolicyAssistant(
    userPrompt: string,
    policy?: EducationPolicy
  ): Promise<{
    answer: string;
    citedClause: string;
    source: 'gemini_api' | 'continuity_rule_engine';
    disclaimer: string;
  }> {
    // If no API key or network restricted, use deterministic local engine
    if (!this.isConfigured()) {
      const fallbackResult = ContinuityIntelligence.queryPolicyAssistant(userPrompt, policy);
      return {
        answer: fallbackResult.answer,
        citedClause: fallbackResult.citedClause,
        source: 'continuity_rule_engine',
        disclaimer: 'Advisory analysis generated by EduShield Local Continuity Intelligence Engine. Not a binding legal coverage determination.',
      };
    }

    try {
      const systemInstruction = 
        'You are the EduShield Continuity Intelligence Assistant. Your role is strictly advisory. ' +
        'You explain education insurance clauses, coverage limits, deductibles, waiting periods, and university escrow fee payments. ' +
        'Always reference specific clause numbers. Never approve, reject or authorize claims. Be concise, professional, and transparent.';

      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${this.apiKey}`,
        {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [
              {
                role: 'user',
                parts: [
                  { text: systemInstruction },
                  { text: `Policy Details: ${policy ? JSON.stringify(policy) : 'Standard EduShield Plan'}` },
                  { text: `User Question: ${userPrompt}` }
                ]
              }
            ],
            generationConfig: {
              temperature: 0.2,
              maxOutputTokens: 500,
            }
          })
        }
      );

      if (!response.ok) {
        throw new Error(`Gemini API returned status ${response.status}`);
      }

      const data = await response.json();
      const textOutput = data.candidates?.[0]?.content?.parts?.[0]?.text;

      if (!textOutput) {
        throw new Error('Empty response from Gemini API');
      }

      return {
        answer: textOutput,
        citedClause: 'Analyzed via Gemini Server Integration with Policy Terms',
        source: 'gemini_api',
        disclaimer: 'Assisted by Gemini AI. Advisory only. Official claim adjudications require licensed claims officer approval.',
      };
    } catch (error) {
      console.warn('Gemini API call failed, activating robust local fallback:', error);
      const fallbackResult = ContinuityIntelligence.queryPolicyAssistant(userPrompt, policy);
      return {
        answer: fallbackResult.answer,
        citedClause: fallbackResult.citedClause,
        source: 'continuity_rule_engine',
        disclaimer: 'Fallback activated: Output generated by EduShield Continuity Intelligence Engine.',
      };
    }
  }
}
